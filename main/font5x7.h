// the glyph of c; '?' for a character the font does not have
static inline const font5x7_t *font5x7_glyph(char c)
{
    const font5x7_t *q = NULL;
    for (size_t i = 0; i < sizeof(font5x7) / sizeof(font5x7[0]); i++) {
        if (font5x7[i].c == c) return &font5x7[i];
        if (font5x7[i].c == '?') q = &font5x7[i];
    }
    return q;
}
